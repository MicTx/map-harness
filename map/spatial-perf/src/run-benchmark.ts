/**
 * The fixed-workload benchmark runner: on the ports the caller wired it
 * generates exactly the frozen fixtures, runs the five workloads plus the
 * worker-cancel leg, samples every segment, admits every final operation's
 * spend before it commits, and evaluates the measured medians against the
 * recorded thresholds. A gate miss fails the run loudly — the recorded gates
 * are measurements on a fixed environment, and a regression is a regression
 * even when the data still comes out right.
 *
 * Determinism: the workload is generated from a fixed seed with a pinned
 * content digest, so every run measures identical bytes and every workload's
 * aggregate must be identical across runs; only wall-clock and memory
 * numbers vary within their bands.
 *
 * @module @map-harness/spatial-perf/run-benchmark
 */
import {
  PERF_ADVISORY_THROUGHPUT,
  PERF_CALIBRATION_PAIRS,
  PERF_CALIBRATION_SPEC,
  PERF_CALIBRATION_WORK_DIGEST,
  PERF_DEPLOYMENT_BUDGETS,
  PERF_METHOD_VERSION,
  PERF_RECORDED_THRESHOLDS,
  PERF_WORKLOAD_FIXTURE,
  perfDigestOf,
  renderPerfIssues,
  validatePerfBudgets,
  validatePerfWorkload,
  type PerfAdvisoryBand,
  type PerfEstimatedCost,
  type PerfHardBudgets,
  type PerfThresholds,
  type PerfWorkload,
} from './contract.ts'
import { perfFixturesOf } from './fixtures.ts'
import { PerfSampler } from './instrument.ts'
import { PerfBudgetLedger } from './budgets.ts'
import { runPerfCalibrationProbe, type PerfCalibrationProbeReading, type PerfCalibrationRunner } from './calibration.ts'
import {
  capturePerfEnvironment,
  evaluateGate,
  evaluateRatioGate,
  gatesPass,
  medianOf,
  type PerfBenchmarkGate,
  type PerfBenchmarkReport,
  type PerfCalibrationPair,
  type PerfCalibrationReport,
  type PerfWorkloadOutcome,
} from './report.ts'
import {
  runLocateVisibilityWorkload,
  runParseRegisterWorkload,
  runRecoveryWorkload,
  runSpatialOpWorkload,
  runTwoPointChain,
  type PerfPorts,
} from './workloads.ts'

/** One benchmark invocation's options (defaults are the frozen fixture, the recorded thresholds, the deployment budgets). */
export interface PerfBenchmarkOptions {
  /** A workload override (must satisfy the workload validation contract). */
  readonly workload?: PerfWorkload
  /** A thresholds override (diagnostic comparisons; the gate lane uses the recorded ones). */
  readonly thresholds?: PerfThresholds
  /** A budgets override (smaller budgets for refusal-path runs). */
  readonly budgets?: PerfHardBudgets
  /** Buffer distance, kilometers, for the spatial-op workload (fixed default). */
  readonly bufferKilometers?: number
  /** Probe implementation injection for deterministic gate tests. */
  readonly calibration?: PerfCalibrationRunner
}

/**
 * Run the full benchmark over the wired ports.
 * @param ports - the production-plane ports (session projection, catalog, worker-cancel).
 * @param options - explicit overrides; defaults are frozen in the contract.
 * @returns the full report; `passed` is the gates' verdict.
 * @throws when the workload/budgets are invalid or any workload's own
 *   assertions fail (wrong fixture, divergent replay, first-point selection).
 */
export async function runPerfBenchmark(
  ports: PerfPorts,
  options: PerfBenchmarkOptions = {},
): Promise<PerfBenchmarkReport> {
  const workload = options.workload ?? PERF_WORKLOAD_FIXTURE
  const thresholds = options.thresholds ?? PERF_RECORDED_THRESHOLDS
  const budgets = options.budgets ?? PERF_DEPLOYMENT_BUDGETS
  const bufferKilometers = options.bufferKilometers ?? 0.5
  const calibrationRunner = options.calibration ?? runPerfCalibrationProbe
  const workloadIssues = validatePerfWorkload(workload)
  if (workloadIssues.length > 0) throw new Error(`benchmark workload rejected: ${renderPerfIssues(workloadIssues)}`)
  const budgetIssues = validatePerfBudgets(budgets)
  if (budgetIssues.length > 0) throw new Error(`benchmark budgets rejected: ${renderPerfIssues(budgetIssues)}`)

  // Freeze check: the generated bytes must match the pinned digest before
  // anything is measured.
  const fixtures = perfFixturesOf(workload)

  const environment = capturePerfEnvironment()
  const heapBefore = process.memoryUsage().heapUsed
  const ledger = new PerfBudgetLedger(budgets)
  const estimatedCosts: PerfEstimatedCost[] = []
  const workloads: Record<string, PerfWorkloadOutcome> = {}
  const probeReadings: PerfBenchmarkReport['calibration']['readings'][number][] = []
  const probeByWorkload = new Map<string, number[]>()

  const readCalibration = (): Readonly<Record<string, PerfCalibrationProbeReading>> => {
    const readings = calibrationRunner(PERF_CALIBRATION_SPEC)
    if (readings.length !== PERF_CALIBRATION_SPEC.length) {
      throw new Error(`calibration returned ${readings.length} sections; expected ${PERF_CALIBRATION_SPEC.length}`)
    }
    const bySection: Record<string, PerfCalibrationProbeReading> = {}
    for (const reading of readings) {
      if (reading.workDigest !== PERF_CALIBRATION_WORK_DIGEST) {
        throw new Error(`calibration work digest mismatch: ${reading.workDigest}`)
      }
      if (!PERF_CALIBRATION_SPEC.some(section => section.section === reading.section)) {
        throw new Error(`calibration returned unknown section: ${reading.section}`)
      }
      if (!Number.isFinite(reading.unitsPerSecond) || reading.unitsPerSecond <= 0) {
        throw new Error(`calibration reading for ${reading.section} is not finite and positive`)
      }
      bySection[reading.section] = reading
    }
    if (Object.keys(bySection).length !== PERF_CALIBRATION_SPEC.length) {
      throw new Error('calibration did not return every frozen section')
    }
    return bySection
  }
  readCalibration()
  const expectedDigest = PERF_CALIBRATION_WORK_DIGEST
  const calibrationFor = (workloadId: string, repetition: number): void => {
    const readings = readCalibration()
    const pair = PERF_CALIBRATION_PAIRS.find(candidate => candidate.workload === workloadId)
    if (pair === undefined) throw new Error(`no calibration pair for workload ${workloadId}`)
    const reading = readings[pair.section]
    if (reading === undefined || reading.workDigest !== expectedDigest) {
      throw new Error(`calibration reading for ${workloadId} is missing or has a different work digest`)
    }
    const values = probeByWorkload.get(workloadId) ?? []
    values.push(reading.unitsPerSecond)
    probeByWorkload.set(workloadId, values)
    probeReadings.push({ workload: pair.workload, repetition, unitsPerSecond: reading.unitsPerSecond })
  }

  // 1. locate/visibility — the interaction path through the real fold.
  const locateSampler = new PerfSampler()
  const locateRaw = await runLocateVisibilityWorkload(
    ports.main,
    locateSampler,
    ledger,
    workload,
    fixtures,
    repetition => calibrationFor('locate-visibility', repetition),
  )
  workloads['locate-visibility'] = outcomeOf(locateRaw, 'folds/s', probeByWorkload.get('locate-visibility'))

  // 2. parse/register — the catalog's admission + transactional publish.
  const parseSampler = new PerfSampler()
  const parseRaw = await runParseRegisterWorkload(
    ports.catalog,
    parseSampler,
    ledger,
    workload,
    fixtures,
    'perf-benchmark-session',
    10_000,
    repetition => calibrationFor('parse-register', repetition),
  )
  workloads['parse-register'] = outcomeOf(parseRaw, 'features/s', probeByWorkload.get('parse-register'))

  // 3. spatial-op — one buffer + area per repeat, codec measured beside it.
  const opSampler = new PerfSampler()
  const opRaw = await runSpatialOpWorkload(
    opSampler,
    ledger,
    workload,
    fixtures,
    bufferKilometers,
    repetition => calibrationFor('spatial-op', repetition),
  )
  workloads['spatial-op'] = outcomeOf(opRaw, 'ops/s', probeByWorkload.get('spatial-op'))

  // 4. recovery-replay — cold replay equals the live fold, on its own session.
  const recoverySampler = new PerfSampler()
  const recoveryRaw = await runRecoveryWorkload(ports.recovery, recoverySampler, ledger, workload)
  workloads['recovery-replay'] = outcomeOf(recoveryRaw, 'ms')
  const flushSample = recoverySampler.records.find(record => record.segment === 'flush')
  const flushWaitMs = flushSample?.wallMs ?? 0

  // 5. two-point-chain — the audit's P0b chain to the folded display.
  const chainSampler = new PerfSampler()
  const chainRaw = await runTwoPointChain(ports.main, ports.catalog, chainSampler, ledger, workload, fixtures, 'perf-benchmark-session', 20_000, bufferKilometers)
  workloads['two-point-chain'] = outcomeOf(chainRaw, 'ms')
  const renderSample = chainSampler.records.find(record => record.segment === 'render')
  const renderDeriveMs = renderSample?.wallMs ?? 0

  // 6. worker-cancel — cancel-request to quiescence on a paced scan.
  const cancelSampler = new PerfSampler()
  const cancel = await ports.cancel.pacedScanAndCancel(until =>
    cancelSampler.wait('cancel', { workload: 'worker-cancel', stage: 'quiescence', unit: 'ms' }, until),
  )
  if (cancel.status !== 'cancelled') {
    throw new Error(`benchmark cancel leg settled "${cancel.status}", expected the cancelled outcome`)
  }
  if (!cancel.stagingClean) {
    throw new Error('benchmark cancel leg left staged residue after quiescence')
  }
  if (cancel.chunksDoneBeforeCancel < 1) {
    throw new Error('benchmark cancel leg cancelled before the first progress point — the pace was not observed')
  }
  const cancelSample = cancelSampler.records.find(record => record.segment === 'cancel')
  const cancelQuiescenceMs = cancelSample?.wallMs ?? 0

  const heapGrowthBytes = Math.max(0, process.memoryUsage().heapUsed - heapBefore)

  // Gates: medians against the recorded bands, stability across repetitions.
  const locate = workloads['locate-visibility']
  const parse = workloads['parse-register']
  const op = workloads['spatial-op']
  const recovery = workloads['recovery-replay']
  const chain = workloads['two-point-chain']
  const worstSpread = Math.max(...[locate, parse, op].map(outcome => outcome.spreadRatio))
  const gates: PerfBenchmarkGate[] = [
    ...PERF_CALIBRATION_PAIRS.map(pair => {
      const outcome = workloads[pair.workload]
      const pairedMedian = outcome?.calibratedMedian ?? 0
      const denominator = outcome === undefined ? 0 : medianOf([...outcome.paired].map(value => value.probe).sort((a, b) => a - b))
      return evaluateRatioGate(
        pair.gate,
        pairedMedian,
        outcome?.median ?? 0,
        denominator,
        thresholds[pair.floorField],
        pair.metric.replace('/s', '/unit'),
        pair.section,
      )
    }),
    evaluateGate('recovery cold replay', recovery?.median ?? 0, thresholds.maxRecoveryReplayMs, '<=', 'ms'),
    evaluateGate('two-point chain wall', chain?.median ?? 0, thresholds.maxChainWallMs, '<=', 'ms'),
    evaluateGate('cancel to quiescence', cancelQuiescenceMs, thresholds.maxCancelQuiescenceMs, '<=', 'ms'),
    evaluateGate('flush durability barrier', flushWaitMs, thresholds.maxFlushWaitMs, '<=', 'ms'),
    evaluateGate('display derivation', renderDeriveMs, thresholds.maxRenderDeriveMs, '<=', 'ms'),
    evaluateGate('run heap growth', heapGrowthBytes, thresholds.maxHeapGrowthBytes, '<=', 'bytes'),
    evaluateGate('repetition spread', worstSpread, thresholds.maxRepetitionSpreadRatio, '<=', '× min'),
  ]

  const calibration = calibrationReportOf(probeReadings, expectedDigest)
  const advisory = advisoryReadingsOf(workloads)

  return {
    methodVersion: PERF_METHOD_VERSION,
    environment,
    workload,
    budgets,
    spend: ledger.accumulated,
    workloads: workloads as PerfBenchmarkReport['workloads'],
    calibration,
    advisory,
    cancelQuiescenceMs: round3(cancelQuiescenceMs),
    flushWaitMs: round3(flushWaitMs),
    renderDeriveMs: round3(renderDeriveMs),
    heapGrowthBytes,
    estimatedCosts,
    telemetryDegraded: [locateSampler, parseSampler, opSampler, recoverySampler, chainSampler, cancelSampler]
      .some(sampler => sampler.degraded),
    gates,
    passed: gatesPass(gates),
  }
}

/** Assemble one workload's report outcome from its raw result. */
function outcomeOf(raw: {
  workload: 'locate-visibility' | 'parse-register' | 'spatial-op' | 'recovery-replay' | 'two-point-chain'
  values: readonly number[]
  aggregate: unknown
  summary: ReturnType<PerfSampler['summary']>
}, unit: string, probes?: readonly number[]): PerfWorkloadOutcome {
  const sorted = [...raw.values].sort((a, b) => a - b)
  const median = medianOf(sorted)
  const low = sorted[0] ?? 0
  const high = sorted[sorted.length - 1] ?? 0
  const spreadRatio = raw.values.length > 1 ? (low === 0 ? Number.MAX_VALUE : round3(high / low)) : 1
  const paired: PerfCalibrationPair[] = probes === undefined
    ? []
    : raw.values.map((target, index) => {
      const probe = probes[index]
      if (probe === undefined || !Number.isFinite(probe) || probe <= 0) {
        throw new Error(`missing or invalid calibration probe for ${raw.workload} repetition ${index}`)
      }
      return { target, probe, ratio: target / probe }
    })
  const calibratedMedian = paired.length === 0
    ? null
    : medianOf(paired.map(pair => pair.ratio).sort((a, b) => a - b))
  return {
    workload: raw.workload,
    unit,
    values: raw.values,
    median,
    paired,
    calibratedMedian,
    spreadRatio,
    aggregate: raw.aggregate,
    aggregateDigest: perfDigestOf(raw.aggregate),
    sampler: raw.summary,
  }
}

function calibrationReportOf(
  readings: readonly PerfBenchmarkReport['calibration']['readings'][number][],
  workDigest: string,
): PerfCalibrationReport {
  const sections = Object.fromEntries(PERF_CALIBRATION_SPEC.map(spec => {
    const sectionReadings = readings
    const rates = sectionReadings.map(reading => reading.unitsPerSecond)
    const minimum = Math.min(...rates)
    const maximum = Math.max(...rates)
    return [spec.section, {
      units: spec.batchUnits * spec.batches,
      batches: spec.batches,
      medianUnitsPerSecond: medianOf([...rates].sort((a, b) => a - b)),
      readingSpreadRatio: maximum / minimum,
      workDigest,
    }]
  })) as PerfCalibrationReport['sections']
  return { workDigest, sections, readings }
}

function advisoryReadingsOf(workloads: Readonly<Record<string, PerfWorkloadOutcome>>): readonly PerfBenchmarkReport['advisory'][number][] {
  const entries: readonly [string, keyof typeof PERF_ADVISORY_THROUGHPUT, string][] = [
    ['locate folds throughput', 'locateFoldsPerSecond', 'locate-visibility'],
    ['parse/register throughput', 'parseFeaturesPerSecond', 'parse-register'],
    ['spatial-op throughput', 'spatialOpsPerSecond', 'spatial-op'],
  ]
  return entries.map(([gate, referenceKey, workloadId]) => {
    const reference: PerfAdvisoryBand = PERF_ADVISORY_THROUGHPUT[referenceKey]
    const measured = workloads[workloadId]?.median ?? 0
    return {
      gate,
      measured,
      unit: reference.unit,
      reference,
      position: measured < reference.retiredFloor
        ? 'below-retired-floor'
        : measured < reference.low ? 'below-reference' : 'at-or-above-reference',
    }
  })
}

function round3(value: number): number {
  return Math.round(value * 1000) / 1000
}
